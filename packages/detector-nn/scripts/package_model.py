"""Packages the DocQuadNet export of scanoficus-ml into `models/` of @scanoficus/detector-nn.

Writes:

- `models/docquadnet-<sha256[:12]>.bin`: the fp16 weights, unchanged, under a content-hashed
  name (caches can keep it forever);
- `models/docquadnet.json`: the graph JSON plus
  - `weights`: `{ file, byteLength, sha256 }`, so a graph never pairs with other weights
    (`loadModel` checks length and SHA-256 and resolves `file` relative to the graph URL);
  - `selfTest`: the 9 outputs of `scanoficus_ml.rawgraph.run_graph` for a constant input of 0.5,
    which the WebGL2 runtime reproduces after initialization to detect a broken GPU path;
- `src/model-files.ts`: the default URLs of both files (`new URL('../models/…',
  import.meta.url)`, which bundlers turn into emitted, hashed assets).

The attribution notice `models/LICENSE.md` is maintained by hand.

Usage (from the repository root, with the scanoficus-ml checkout and its virtualenv):

    PYTHONDONTWRITEBYTECODE=1 ~/src/scanoficus-ml/.venv/bin/python \\
        packages/detector-nn/scripts/package_model.py [--ml ~/src/scanoficus-ml]
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

import numpy as np

PKG = Path(__file__).resolve().parent.parent
MODELS = PKG / "models"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--ml", default=str(Path.home() / "src" / "scanoficus-ml"))
    args = parser.parse_args()
    ml = Path(args.ml)
    sys.path.insert(0, str(ml))
    from scanoficus_ml.rawgraph import run_graph

    export = ml / "export" / "docquadnet"
    graph = json.loads((export / "docquadnet.json").read_text())
    blob = (export / "docquadnet.bin").read_bytes()
    sha = hashlib.sha256(blob).hexdigest()
    name = f"docquadnet-{sha[:12]}.bin"
    weights = np.frombuffer(blob, "<f2").astype(np.float32)
    shape = graph["input"]["shape"]
    heads = run_graph(graph, weights, np.full(shape, 0.5, np.float32))

    MODELS.mkdir(exist_ok=True)
    for old in MODELS.glob("docquadnet-*.bin"):
        if old.name != name:
            old.unlink()
    (MODELS / name).write_bytes(blob)
    graph["weights"] = {"file": name, "byteLength": len(blob), "sha256": sha}
    graph["selfTest"] = {"input": 0.5, "heads": [float(v) for v in heads]}
    (MODELS / "docquadnet.json").write_text(json.dumps(graph, indent=1) + "\n")
    (PKG / "src" / "model-files.ts").write_text(
        "// Generated by scripts/package_model.py; do not edit.\n"
        "/** Default URL of the DocQuadNet graph shipped in the package (`models/docquadnet.json`). */\n"
        "export const DOCQUADNET_GRAPH_URL: URL = new URL(\n"
        "  '../models/docquadnet.json',\n"
        "  import.meta.url,\n"
        ");\n"
        "/** Default URL of the DocQuadNet weights shipped in the package (content-hashed name). */\n"
        "export const DOCQUADNET_WEIGHTS_URL: URL = new URL(\n"
        f"  '../models/{name}',\n"
        "  import.meta.url,\n"
        ");\n"
    )
    print(f"{name}: {len(blob)} bytes, self-test heads {np.round(heads, 4).tolist()}")


if __name__ == "__main__":
    main()
